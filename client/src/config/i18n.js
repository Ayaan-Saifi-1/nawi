export function useTranslation() {
  const language = useThemeStore((s) => s.language);

  const t = (key, fallback = '') => {
    const langDict = TRANSLATIONS[language] || TRANSLATIONS.EN;
    return langDict[key] || TRANSLATIONS.EN[key] || fallback || key;
  };

  return { t, language };
}
